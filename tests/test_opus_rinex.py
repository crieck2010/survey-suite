"""Pytest suite for the survey-opus RINEX header engine.

Fixtures are real files under tests/fixtures/rinex/ (generated by
/tmp/gen_opus_fixtures.py with exact 80-column RINEX header layouts).

NOTE on imports: this module first tries the normal package import
(``from survey_opus.rinex import ...``). The sibling ``client.py`` owned by
another builder does not exist yet and the package ``__init__`` imports it,
so the fallback loads ``rinex.py`` directly by file path -- ``rinex.py`` is
pure stdlib with no relative imports, so it loads standalone. Once
``client.py`` lands, the normal import path takes over automatically.
"""

import importlib.util
from datetime import datetime
from pathlib import Path

import pytest

FIX = Path(__file__).parent / "fixtures" / "rinex"
_RINEX_SRC = Path(__file__).resolve().parents[1] / "src" / "survey_opus" / "rinex.py"


def _load_api():
    try:
        from survey_opus.rinex import (  # noqa: F401
            RinexError,
            RinexHeader,
            parse_header,
            validate_for_opus,
        )
        return RinexError, RinexHeader, parse_header, validate_for_opus
    except ImportError:
        spec = importlib.util.spec_from_file_location(
            "survey_opus_rinex_standalone", _RINEX_SRC
        )
        mod = importlib.util.module_from_spec(spec)
        assert spec.loader is not None
        # Register before exec: dataclasses resolves annotations via
        # sys.modules[cls.__module__].
        import sys

        sys.modules[spec.name] = mod
        spec.loader.exec_module(mod)
        return mod.RinexError, mod.RinexHeader, mod.parse_header, mod.validate_for_opus


RinexError, RinexHeader, parse_header, validate_for_opus = _load_api()


def fx(name):
    return str(FIX / name)


# ---------------------------------------------------------------------------
# RINEX 2.11 parsing
# ---------------------------------------------------------------------------


def test_rinex211_version_marker_constellation():
    h = parse_header(fx("valid_v211.o"))
    assert h.rinex_version == "2.11"
    assert h.marker_name == "CHAR001"
    assert h.constellations == {"G"}
    assert isinstance(h, RinexHeader)


def test_rinex211_antenna():
    h = parse_header(fx("valid_v211.o"))
    assert h.antenna_type == "TRM57971.00"
    assert h.antenna_height == pytest.approx(1.5423)


def test_rinex211_times_and_span():
    h = parse_header(fx("valid_v211.o"))
    assert h.start_time == datetime(2026, 10, 8, 12, 0, 0)
    assert h.end_time == datetime(2026, 10, 8, 16, 30, 0)
    assert (h.end_time - h.start_time).total_seconds() == pytest.approx(4.5 * 3600)


def test_rinex211_obs_types_flat():
    h = parse_header(fx("valid_v211.o"))
    assert h.obs_types == {
        "G": ["C1", "P1", "P2", "L1", "L2", "D1", "D2", "S1", "S2"]
    }


def test_rinex211_interval_position():
    h = parse_header(fx("valid_v211.o"))
    assert h.interval == pytest.approx(15.0)
    assert h.approx_position == pytest.approx(
        (1130342.5012, -4835432.1234, 3998123.4567)
    )


def test_rinex2_two_digit_year_pivot():
    h = parse_header(fx("y2k_v211.o"))
    assert h.start_time == datetime(1998, 6, 15, 9, 30, 0)
    assert h.end_time == datetime(1998, 6, 15, 13, 30, 0)


