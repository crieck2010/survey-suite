def test_validate_clean_v211():
    assert validate_for_opus(parse_header(fx("valid_v211.o"))) == []


def test_validate_clean_v304():
    assert validate_for_opus(parse_header(fx("valid_v304.25o"))) == []


def test_validate_zero_height():
    problems = validate_for_opus(parse_header(fx("zero_height.o")))
    assert any("antenna height" in p for p in problems)
    assert len(problems) == 1


def test_validate_placeholder_antenna():
    problems = validate_for_opus(parse_header(fx("placeholder_ant.o")))
    assert any("antenna type" in p for p in problems)
    assert len(problems) == 1


def test_validate_short_span_below_rapid_static_floor():
    problems = validate_for_opus(parse_header(fx("short_span.o")))
    assert any("15 min" in p for p in problems)
    assert not any(p.startswith("WARN:") for p in problems)


def test_validate_warn_span_under_2h():
    # 45 min span: submittable for rapid-static, warns for static.
    problems = validate_for_opus(parse_header(fx("warn_span.o")))
    assert len(problems) == 1
    assert problems[0].startswith("WARN:")
    assert "2 h" in problems[0]


def test_validate_missing_last_obs():
    problems = validate_for_opus(parse_header(fx("no_last_obs.o")))
    assert any("TIME OF LAST OBS" in p for p in problems)


def test_validate_single_frequency():
    problems = validate_for_opus(parse_header(fx("single_freq.o")))
    assert any("L2" in p for p in problems)
    assert len(problems) == 1


def test_rinexerror_is_valueerror():
    assert issubclass(RinexError, ValueError)
