def test_rinex304_version_marker_constellations():
    h = parse_header(fx("valid_v304.25o"))
    assert h.rinex_version == "3.04"
    assert h.marker_name == "MOON01"
    assert h.constellations == {"G", "R", "E"}


def test_rinex304_sys_obs_types():
    h = parse_header(fx("valid_v304.25o"))
    assert h.obs_types["G"] == ["C1C", "L1C", "D1C", "S1C", "C2W", "L2W", "D2W", "S2W"]
    assert h.obs_types["R"] == ["C1C", "L1C", "D1C", "S1C", "C2P", "L2P", "D2P", "S2P"]
    assert h.obs_types["E"] == ["C1X", "L1X", "D1X", "S1X", "C5X", "L5X", "D5X", "S5X"]


def test_rinex304_time_system_tags_handled():
    # First-obs line carries a "GPS" tag, last-obs a "UTC" tag.
    h = parse_header(fx("valid_v304.25o"))
    assert h.start_time == datetime(2026, 10, 6, 8, 0, 0)
    assert h.end_time == datetime(2026, 10, 6, 11, 0, 0)
    assert h.interval == pytest.approx(30.0)


def test_rinex304_antenna_and_height():
    h = parse_header(fx("valid_v304.25o"))
    assert h.antenna_type == "LEIAR25.R4"
    assert h.antenna_height == pytest.approx(2.0)


def test_leap_seconds_ignored_gracefully():
    # Both valid fixtures carry LEAP SECONDS lines (+ continuation lines).
    h2 = parse_header(fx("valid_v211.o"))
    h3 = parse_header(fx("valid_v304.25o"))
    assert h2.marker_name == "CHAR001"
    assert h3.marker_name == "MOON01"


# ---------------------------------------------------------------------------
# Malformed inputs -> RinexError
# ---------------------------------------------------------------------------


def test_missing_file_raises():
    with pytest.raises(RinexError, match="not found or unreadable"):
        parse_header(fx("does_not_exist.o"))


def test_non_rinex_file_raises():
    with pytest.raises(RinexError, match="not a RINEX observation file"):
        parse_header(fx("non_rinex.txt"))


def test_bad_first_line_raises():
    p = FIX / "bad_first_line.o"
    p.write_text("GARBAGE LINE THAT IS NOT RINEX\n" + "x" * 80 + "\n")
    try:
        with pytest.raises(RinexError, match="bad first line"):
            parse_header(str(p))
    finally:
        p.unlink()


def test_unparseable_version_raises():
    with pytest.raises(RinexError, match="unparseable RINEX version"):
        parse_header(fx("bad_version.o"))


def test_truncated_header_raises():
    with pytest.raises(RinexError, match="no END OF HEADER"):
        parse_header(fx("truncated.o"))


def test_missing_marker_name_raises():
    with pytest.raises(RinexError, match="missing MARKER NAME"):
        parse_header(fx("no_marker.o"))


def test_empty_file_raises():
    p = FIX / "empty.o"
    p.write_text("")
    try:
        with pytest.raises(RinexError, match="not a RINEX observation file"):
            parse_header(str(p))
    finally:
        p.unlink()


